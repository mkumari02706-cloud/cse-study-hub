/**
 * Extracts standard 11-character YouTube Video ID from various URL patterns
 */
function extractVideoId(urlOrId) {
  if (!urlOrId || typeof urlOrId !== 'string') return null;

  const trimmed = urlOrId.trim();

  // If already an 11-character video ID
  if (/^[a-zA-Z0-9_-]{11}$/.test(trimmed)) {
    return trimmed;
  }

  // Common YouTube URL regex patterns
  const patterns = [
    /(?:https?:\/\/)?(?:www\.)?youtube\.com\/watch\?(?:.*&)?v=([a-zA-Z0-9_-]{11})/i,
    /(?:https?:\/\/)?(?:www\.)?youtu\.be\/([a-zA-Z0-9_-]{11})/i,
    /(?:https?:\/\/)?(?:www\.)?youtube\.com\/embed\/([a-zA-Z0-9_-]{11})/i,
    /(?:https?:\/\/)?(?:www\.)?youtube\.com\/shorts\/([a-zA-Z0-9_-]{11})/i,
    /(?:https?:\/\/)?(?:www\.)?youtube\.com\/v\/([a-zA-Z0-9_-]{11})/i,
    /(?:https?:\/\/)?(?:www\.)?youtube\.com\/live\/([a-zA-Z0-9_-]{11})/i,
    /(?:https?:\/\/)?m\.youtube\.com\/watch\?(?:.*&)?v=([a-zA-Z0-9_-]{11})/i
  ];

  for (const regex of patterns) {
    const match = trimmed.match(regex);
    if (match && match[1]) {
      return match[1];
    }
  }

  return null;
}

/**
 * Decodes common HTML / XML entities
 */
function decodeEntities(text) {
  if (!text || typeof text !== 'string') return '';
  return text
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec) => String.fromCodePoint(parseInt(dec, 10)));
}

/**
 * Fetches video metadata via YouTube oEmbed or Google YouTube Data API v3 (if key configured)
 */
async function fetchVideoMetadata(videoId) {
  if (!videoId) return null;

  const cacheKey = `yt_meta_${videoId}`;
  const cached = cache.get(cacheKey);
  if (cached) return cached;

  const defaultMeta = {
    title: `YouTube Lecture (${videoId})`,
    author: 'YouTube Instructor',
    thumbnail: `https://img.youtube.com/vi/${videoId}/hqdefault.jpg`,
    videoUrl: `https://www.youtube.com/watch?v=${videoId}`
  };

  // 1. Try YouTube Data API v3 if API key configured
  const apiKey = process.env.YOUTUBE_API_KEY || process.env.GOOGLE_API_KEY;
  if (apiKey && apiKey.trim()) {
    try {
      const apiUrl = `https://www.googleapis.com/youtube/v3/videos?id=${encodeURIComponent(videoId)}&part=snippet&key=${encodeURIComponent(apiKey.trim())}`;
      const apiRes = await fetch(apiUrl);
      if (apiRes.ok) {
        const apiData = await apiRes.json();
        const item = apiData.items && apiData.items[0];
        if (item && item.snippet) {
          const meta = {
            title: item.snippet.title || defaultMeta.title,
            author: item.snippet.channelTitle || defaultMeta.author,
            thumbnail: (item.snippet.thumbnails && item.snippet.thumbnails.high && item.snippet.thumbnails.high.url) || defaultMeta.thumbnail,
            videoUrl: `https://www.youtube.com/watch?v=${videoId}`
          };
          cache.set(cacheKey, meta, 24 * 60 * 60 * 1000); // 24hr cache
          return meta;
        }
      }
    } catch {
      // Fall through to oEmbed
    }
  }

  // 2. Try official YouTube oEmbed
  try {
    const oembedUrl = `https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v=${encodeURIComponent(videoId)}&format=json`;
    const res = await fetch(oembedUrl);
    if (res.ok) {
      const data = await res.json();
      const meta = {
        title: data.title || defaultMeta.title,
        author: data.author_name || defaultMeta.author,
        thumbnail: defaultMeta.thumbnail,
        videoUrl: `https://www.youtube.com/watch?v=${videoId}`
      };
      cache.set(cacheKey, meta, 24 * 60 * 60 * 1000);
      return meta;
    }
  } catch {
    // Ignore and return default
  }

  cache.set(cacheKey, defaultMeta, 60 * 60 * 1000);
  return defaultMeta;
}

/**
 * Formats transcript items into readable text with timestamps and clean text
 */
function formatTranscript(items) {
  if (!items || !items.length) {
    return {
      rawItems: [],
      timestampedText: '',
      fullText: '',
      wordCount: 0
    };
  }

  const timestamped = items.map(item => {
    let totalSecs = 0;
    if (item.offsetSec !== undefined) {
      totalSecs = item.offsetSec;
    } else if (item.offset > 1000 || items[items.length - 1]?.offset > 1800) {
      totalSecs = Math.floor((item.offset || 0) / 1000);
    } else {
      totalSecs = Math.floor(item.offset || 0);
    }
    const mins = Math.floor(totalSecs / 60).toString().padStart(2, '0');
    const secs = (totalSecs % 60).toString().padStart(2, '0');
    const cleanText = (item.text || '').replace(/\s+/g, ' ').trim();
    return `[${mins}:${secs}] ${cleanText}`;
  }).filter(line => line.length > 8).join('\n');

  const cleanText = items.map(i => (i.text || '').trim()).filter(Boolean).join(' ');

  return {
    rawItems: items,
    timestampedText: timestamped,
    fullText: cleanText,
    wordCount: cleanText.split(/\s+/).filter(Boolean).length
  };
}

/**
 * Parses XML transcript text supporting both srv3 format (<p t="ms" d="ms">)
 * and classic format (<text start="s" dur="s">)
 */
function parseTranscriptXml(xml, lang = 'en') {
  if (!xml || typeof xml !== 'string') return [];
  const results = [];

  // Format 1: srv3 (<p t="ms" d="ms"><s>word</s> or <w t="ms">word</w> or text</p>)
  const pRegex = /<p\s+t="(\d+)"\s+d="(\d+)"[^>]*>([\s\S]*?)<\/p>/g;
  let match;
  while ((match = pRegex.exec(xml)) !== null) {
    const startMs = parseInt(match[1], 10);
    const durMs = parseInt(match[2], 10);
    const inner = match[3];
    let text = '';
    const sRegex = /<s[^>]*>([^<]*)<\/s>/g;
    let sMatch;
    while ((sMatch = sRegex.exec(inner)) !== null) {
      text += sMatch[1];
    }
    if (!text) {
      text = inner.replace(/<[^>]+>/g, '');
    }
    text = decodeEntities(text).replace(/\s+/g, ' ').trim();
    if (text) {
      results.push({
        text,
        duration: durMs,
        offset: startMs,
        offsetSec: Math.floor(startMs / 1000),
        lang
      });
    }
  }

  if (results.length > 0) return results;

  // Format 2: Classic (<text start="sec" dur="sec">content</text>)
  const textRegex = /<text\s+start="([^"]*)"(?:\s+dur="([^"]*)")?[^>]*>([\s\S]*?)<\/text>/g;
  let tMatch;
  while ((tMatch = textRegex.exec(xml)) !== null) {
    const startSec = parseFloat(tMatch[1]) || 0;
    const durSec = parseFloat(tMatch[2]) || 0;
    const text = decodeEntities(tMatch[3].replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim();
    if (text) {
      results.push({
        text,
        offset: Math.round(startSec * 1000),
        offsetSec: Math.floor(startSec),
        duration: Math.round(durSec * 1000),
        lang
      });
    }
  }

  return results;
}

/**
 * Retry helper with exponential backoff and jitter
 * Does NOT retry on rate-limit (429/Captcha), 404, or captions-disabled errors.
 */
async function withExponentialBackoff(fn, { maxRetries = 2, baseDelayMs = 400 } = {}) {
  let attempt = 0;
  while (true) {
    try {
      return await fn();
    } catch (err) {
      attempt++;
      const isRateLimit = err && (
        err.message?.includes('too many requests') ||
        err.message?.includes('captcha') ||
        err.message?.includes('g-recaptcha') ||
        err.status === 429
      );
      const isPermanent = err && (
        err.status === 404 ||
        err.message?.includes('disabled') ||
        err.message?.includes('no longer available') ||
        err.message?.includes('Impossible to retrieve')
      );

      if (isRateLimit) {
        // Immediately record cooldown and do not retry
        cache.setRateLimitCooldown(60 * 1000, 'YouTube IP rate limit / Captcha detected');
        throw err;
      }

      if (isPermanent || attempt > maxRetries) {
        throw err;
      }

      const jitter = Math.floor(Math.random() * 150);
      const delay = baseDelayMs * Math.pow(2, attempt - 1) + jitter;
      await new Promise(resolve => setTimeout(resolve, delay));
    }
  }
}

/**
 * Strategy 1: Multi-Client InnerTube Player API
 * Uses mobile and VR client contexts which bypass desktop BotGuard / PoToken restrictions.
 * Accurately extracts both manual closed captions and auto-generated (ASR) subtitles.
 */
async function fetchViaInnerTube(videoId, requestedLang = 'en') {
  const clients = [
    {
      name: 'ANDROID',
      version: '20.10.38',
      userAgent: 'com.google.android.youtube/20.10.38 (Linux; U; Android 14; Pixel 7 Pro Build/UQ1A.240205.004)',
      headers: {
        'X-YouTube-Client-Name': '3',
        'X-YouTube-Client-Version': '20.10.38'
      }
    },
    {
      name: 'ANDROID_VR',
      version: '1.61.48',
      userAgent: 'Mozilla/5.0 (Linux; Android 12; Quest 3) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/123.0.0.0 Mobile Safari/537.36',
      headers: {
        'X-YouTube-Client-Name': '72',
        'X-YouTube-Client-Version': '1.61.48'
      }
    },
    {
      name: 'IOS',
      version: '19.45.4',
      userAgent: 'com.google.ios.youtube/19.45.4 (iPhone16,2; U; CPU iOS 17_5 like Mac OS X)',
      headers: {
        'X-YouTube-Client-Name': '5',
        'X-YouTube-Client-Version': '19.45.4'
      }
    }
  ];

  for (const client of clients) {
    try {
      const playerUrl = 'https://www.youtube.com/youtubei/v1/player?prettyPrint=false';
      const res = await withExponentialBackoff(async () => {
        return await fetch(playerUrl, {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'User-Agent': client.userAgent,
            ...(client.headers || {})
          },
          body: JSON.stringify({
            context: {
              client: {
                clientName: client.name,
                clientVersion: client.version,
                hl: requestedLang || 'en',
                gl: 'US'
              }
            },
            videoId
          })
        });
      });

      if (!res.ok) continue;

      const data = await res.json();
      const playability = data?.playabilityStatus?.status;
      const reason = data?.playabilityStatus?.reason || '';

      if (playability === 'LOGIN_REQUIRED') {
        const isBotChallenge = !reason || /bot|captcha|unusual traffic|sign in to confirm|verify/i.test(reason);
        if (isBotChallenge) {
          // Continue to next mobile client rather than aborting immediately
          continue;
        }
      }

      if (playability !== 'OK') {
        continue;
      }

      const captionTracks = data?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
      if (!Array.isArray(captionTracks) || captionTracks.length === 0) {
        continue;
      }

      // Pick the best track from the track list:
      // 1. Requested language (exact, manual)
      let chosenTrack = captionTracks.find(t => t.languageCode === requestedLang && t.kind !== 'asr');
      // 2. Requested language (exact, auto-generated ASR)
      if (!chosenTrack) {
        chosenTrack = captionTracks.find(t => t.languageCode === requestedLang);
      }
      // 3. Requested language (prefix, manual)
      if (!chosenTrack) {
        chosenTrack = captionTracks.find(t => t.languageCode && t.languageCode.startsWith(requestedLang) && t.kind !== 'asr');
      }
      // 4. Requested language (prefix, auto-generated)
      if (!chosenTrack) {
        chosenTrack = captionTracks.find(t => t.languageCode && t.languageCode.startsWith(requestedLang));
      }
      // 5. English track (manual)
      if (!chosenTrack && requestedLang !== 'en') {
        chosenTrack = captionTracks.find(t => (t.languageCode === 'en' || t.languageCode?.startsWith('en')) && t.kind !== 'asr');
      }
      // 6. English track (auto-generated)
      if (!chosenTrack && requestedLang !== 'en') {
        chosenTrack = captionTracks.find(t => t.languageCode === 'en' || t.languageCode?.startsWith('en'));
      }
      // 7. Hindi track (manual)
      if (!chosenTrack && requestedLang !== 'hi') {
        chosenTrack = captionTracks.find(t => (t.languageCode === 'hi' || t.languageCode?.startsWith('hi')) && t.kind !== 'asr');
      }
      // 8. Hindi track (auto-generated)
      if (!chosenTrack && requestedLang !== 'hi') {
        chosenTrack = captionTracks.find(t => t.languageCode === 'hi' || t.languageCode?.startsWith('hi'));
      }
      // 9. First available manual track
      if (!chosenTrack) {
        chosenTrack = captionTracks.find(t => t.kind !== 'asr');
      }
      // 10. First available track (including auto-generated)
      if (!chosenTrack) {
        chosenTrack = captionTracks[0];
      }

      if (!chosenTrack || !chosenTrack.baseUrl) continue;

      const trackUrl = new URL(chosenTrack.baseUrl);
      if (!trackUrl.hostname.endsWith('.youtube.com')) continue;

      // Fetch the caption track content
      const trackRes = await withExponentialBackoff(async () => {
        return await fetch(chosenTrack.baseUrl, {
          headers: {
            'User-Agent': client.userAgent,
            'Accept-Language': requestedLang
          }
        });
      });

      if (!trackRes.ok) continue;

      const xml = await trackRes.text();
      const items = parseTranscriptXml(xml, chosenTrack.languageCode || requestedLang);
      if (items.length > 0) {
        return {
          items,
          language: chosenTrack.languageCode || requestedLang,
          isAutoGenerated: Boolean(chosenTrack.kind === 'asr'),
          trackName: chosenTrack.name?.runs?.[0]?.text || chosenTrack.name?.simpleText || ''
        };
      }
    } catch {
      continue;
    }
  }

  return null;
}

/**
 * Strategy 2: Web page HTML scraping fallback
 * Scrapes ytInitialPlayerResponse from the YouTube watch page.
 */
async function fetchViaWebPageScraping(videoId, requestedLang = 'en') {
  try {
    const pageUrl = `https://www.youtube.com/watch?v=${encodeURIComponent(videoId)}`;
    const res = await withExponentialBackoff(async () => {
      return await fetch(pageUrl, {
        headers: {
          'User-Agent': getRandomUserAgent(),
          'Accept-Language': requestedLang
        }
      });
    });

    if (!res.ok) return null;
    const html = await res.text();
    if (html.includes('class="g-recaptcha"')) {
      return null;
    }

    const startToken = 'var ytInitialPlayerResponse = ';
    let startIndex = html.indexOf(startToken);
    let playerResponse = null;

    if (startIndex !== -1) {
      const jsonStart = startIndex + startToken.length;
      let depth = 0;
      for (let i = jsonStart; i < html.length; i++) {
        if (html[i] === '{') depth++;
        else if (html[i] === '}') {
          depth--;
          if (depth === 0) {
            try {
              playerResponse = JSON.parse(html.slice(jsonStart, i + 1));
            } catch {}
            break;
          }
        }
      }
    }

    if (!playerResponse) {
      const match = html.match(/ytInitialPlayerResponse\s*=\s*({.+?});(?:var|\s*<\/script>)/s);
      if (match && match[1]) {
        try { playerResponse = JSON.parse(match[1]); } catch {}
      }
    }

    const captionTracks = playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
    if (!Array.isArray(captionTracks) || captionTracks.length === 0) {
      return null;
    }

    let chosenTrack = captionTracks.find(t => t.languageCode === requestedLang && t.kind !== 'asr') ||
                      captionTracks.find(t => t.languageCode === requestedLang) ||
                      captionTracks.find(t => t.languageCode && t.languageCode.startsWith(requestedLang)) ||
                      captionTracks.find(t => t.languageCode === 'en' || t.languageCode?.startsWith('en')) ||
                      captionTracks[0];

    if (!chosenTrack || !chosenTrack.baseUrl) return null;

    const trackRes = await fetch(chosenTrack.baseUrl, {
      headers: {
        'User-Agent': getRandomUserAgent(),
        'Accept-Language': requestedLang
      }
    });

    if (!trackRes.ok) return null;
    const xml = await trackRes.text();
    const items = parseTranscriptXml(xml, chosenTrack.languageCode || requestedLang);
    if (items.length > 0) {
      return {
        items,
        language: chosenTrack.languageCode || requestedLang,
        isAutoGenerated: Boolean(chosenTrack.kind === 'asr')
      };
    }
  } catch {
    return null;
  }
  return null;
}

/**
 * Strategy 3: Standard youtube-transcript library fallback (with flexible language matching)
 */
async function fetchViaYoutubeTranscriptLib(videoId, requestedLang = 'en') {
  if (cache.isCooldownActive()) {
    return null;
  }

  try {
    let items;
    try {
      items = await YoutubeTranscript.fetchTranscript(videoId, { lang: requestedLang });
    } catch {
      // Fallback: try without language constraint to grab the available subtitle track
      items = await YoutubeTranscript.fetchTranscript(videoId);
    }

    if (items && items.length > 0) {
      return {
        items,
        language: items[0].lang || requestedLang,
        isAutoGenerated: false
      };
    }
  } catch (err) {
    const msg = err.message || '';
    if (msg.includes('too many requests') || msg.includes('captcha') || msg.includes('g-recaptcha')) {
      cache.setRateLimitCooldown(60 * 1000, 'YouTube rate limit detected by library');
    }
  }

  return null;
}

/**
 * Strategy 4: Direct TimedText API
 */
async function fetchViaTimedText(videoId, lang = 'en') {
  const timedTextUrls = [
    `https://www.youtube.com/api/timedtext?v=${videoId}&lang=${lang}&fmt=srv3`,
    `https://www.youtube.com/api/timedtext?v=${videoId}&lang=${lang}`
  ];

  for (const url of timedTextUrls) {
    try {
      const res = await withExponentialBackoff(async () => {
        return await fetch(url, {
          headers: {
            'User-Agent': getRandomUserAgent(),
            'Accept-Language': lang
          }
        });
      });

      if (!res.ok) continue;
      const body = await res.text();
      if (!body || body.includes('class="g-recaptcha"') || body.includes('consent.youtube.com') || body.includes('sorry/index') || body.includes('unusual traffic')) {
        continue;
      }

      const items = parseTranscriptXml(body, lang);
      if (items.length > 0) {
        return { items, language: lang, isAutoGenerated: false };
      }
    } catch {
      continue;
    }
  }

  return null;
}

/**
 * Categorizes an error and provides actionable, clear messaging with alternatives
 */
function categorizeError(err, videoId) {
  const msg = (err && err.message) || 'Unknown error occurred.';
  const isProd = process.env.NODE_ENV === 'production';
  const isCloudEnv = isProd || Boolean(process.env.RENDER || process.env.VERCEL || process.env.AWS_REGION);

  // 1. Rate Limit / CAPTCHA challenge
  if (
    cache.isCooldownActive() ||
    err?.code === 'RATE_LIMITED' ||
    msg.includes('too many requests') ||
    msg.includes('captcha') ||
    msg.includes('g-recaptcha') ||
    msg.includes('rate-limit')
  ) {
    const remaining = cache.getCooldownRemainingSec() || 60;
    return {
      errorCode: 'RATE_LIMITED',
      isRateLimited: true,
      error: `YouTube request was temporarily rate-limited (cooldown active for ${remaining}s).`,
      details: 'YouTube has temporarily rate-limited automated queries from this server IP. Please retry shortly.',
      canFallbackManual: true,
      canUploadMedia: true,
      suggestedAction: 'retry_later',
      environment: {
        isProduction: isProd,
        isCloudDatacenter: isCloudEnv,
        cooldownRemainingSec: remaining
      },
      productionGuidance: {
        videoUrl: `https://www.youtube.com/watch?v=${videoId}`,
        message: 'Rate limit guidance:',
        steps: [
          'Wait for the rate limit cooldown to expire',
          'Ensure valid public YouTube URLs are provided'
        ]
      }
    };
  }

  // 2. Disabled Captions
  if (err?.code === 'CAPTIONS_DISABLED' || msg.includes('disabled') || msg.includes('Disabled')) {
    return {
      errorCode: 'CAPTIONS_DISABLED',
      error: `Captions are disabled by the creator for this video (${videoId}).`,
      details: 'The video publisher has turned off closed captions and subtitles.',
      canFallbackManual: true,
      canUploadMedia: true,
      suggestedAction: 'captions_disabled'
    };
  }

  // 3. Video Unavailable / Private / Deleted
  if (err?.code === 'VIDEO_UNAVAILABLE' || msg.includes('unavailable') || msg.includes('no longer available') || msg.includes('private')) {
    return {
      errorCode: 'VIDEO_UNAVAILABLE',
      error: `This YouTube video is unavailable, private, or not found (${videoId}).`,
      details: 'Please verify that the video is public and accessible.',
      canFallbackManual: true,
      canUploadMedia: true,
      suggestedAction: 'check_url'
    };
  }

  // 4. Network or Timeout Failure
  if (msg.includes('fetch failed') || msg.includes('ETIMEDOUT') || msg.includes('ECONNRESET') || msg.includes('network')) {
    return {
      errorCode: 'NETWORK_ERROR',
      error: `Network timeout connecting to YouTube (${msg.slice(0, 100)}).`,
      details: 'Could not reach YouTube servers. Please try again.',
      canFallbackManual: true,
      canUploadMedia: true,
      suggestedAction: 'retry_later'
    };
  }

  // 5. General Transcript Not Available
  return {
    errorCode: 'TRANSCRIPT_NOT_AVAILABLE',
    error: `No captions or subtitles are available for this video (${videoId}).`,
    details: 'The video does not have available subtitles or auto-generated captions.',
    canFallbackManual: true,
    canUploadMedia: true,
    suggestedAction: 'no_captions'
  };
}

/**
 * Main YouTube Transcript Fetcher
 * Implements request caching, multi-client InnerTube execution, web scraping fallback,
 * and robust parsing for both manual and auto-generated captions.
 */
async function fetchTranscript(urlOrId, requestedLang = 'en', options = {}) {
  const videoId = extractVideoId(urlOrId);
  if (!videoId) {
    return {
      success: false,
      errorCode: 'INVALID_URL',
      error: 'Invalid YouTube URL or Video ID. Please provide a valid YouTube link.',
      canFallbackManual: true,
      canUploadMedia: true
    };
  }

  // 1. Check in-memory cache
  const cacheKey = `yt_transcript_${videoId}_${requestedLang}`;
  const cachedResult = cache.get(cacheKey);
  if (cachedResult && !options.skipCache) {
    return {
      ...cachedResult,
      isCached: true
    };
  }

  // 2. Fetch video metadata in parallel
  const metadataPromise = fetchVideoMetadata(videoId);

  // 3. Check if IP is currently under rate-limit cooldown
  if (cache.isCooldownActive()) {
    const metadata = await metadataPromise;
    const errorInfo = categorizeError(new Error('Rate limit cooldown active'), videoId);
    return {
      success: false,
      videoId,
      metadata,
      ...errorInfo
    };
  }

  let transcriptData = null;
  let lastError = null;

  // 4. Strategy 1: Mobile InnerTube Player API (works directly on Render & localhost)
  try {
    transcriptData = await fetchViaInnerTube(videoId, requestedLang);
  } catch (err) {
    lastError = err;
  }

  // 5. Strategy 2: Web page HTML scraping fallback
  if (!transcriptData && !cache.isCooldownActive()) {
    try {
      transcriptData = await fetchViaWebPageScraping(videoId, requestedLang);
    } catch (err) {
      lastError = err;
    }
  }

  // 6. Strategy 3: Standard youtube-transcript library fallback
  if (!transcriptData && !cache.isCooldownActive()) {
    try {
      transcriptData = await fetchViaYoutubeTranscriptLib(videoId, requestedLang);
    } catch (err) {
      lastError = err;
    }
  }

  // 7. Strategy 4: Direct TimedText API fallback
  if (!transcriptData && !cache.isCooldownActive()) {
    try {
      transcriptData = await fetchViaTimedText(videoId, requestedLang);
    } catch (err) {
      lastError = err;
    }
  }

  const metadata = await metadataPromise;

  // 8. Handle failure
  if (!transcriptData || !transcriptData.items || transcriptData.items.length === 0) {
    // Short negative cache (90s) to prevent hammering YouTube on repeated clicks
    cache.set(`yt_negative_${videoId}`, true, 90 * 1000);

    const errorInfo = categorizeError(lastError, videoId);
    return {
      success: false,
      videoId,
      metadata,
      ...errorInfo
    };
  }

  // 9. Format successful transcript
  const formatted = formatTranscript(transcriptData.items);
  const result = {
    success: true,
    videoId,
    metadata,
    language: transcriptData.language || requestedLang,
    isAutoGenerated: Boolean(transcriptData.isAutoGenerated),
    wordCount: formatted.wordCount,
    timestampedText: formatted.timestampedText,
    fullText: formatted.fullText,
    rawItems: formatted.rawItems
  };

  // Cache successful result (1 hour TTL)
  cache.set(cacheKey, result, 60 * 60 * 1000);

  return result;
}

/**
 * Ingests and caches a transcript directly into memory and persistent disk cache
 */
function cacheTranscript(videoId, transcriptData, lang = 'en') {
  if (!videoId || !transcriptData) return false;
  const cleanId = extractVideoId(videoId) || videoId;
  const cacheKey = `yt_transcript_${cleanId}_${lang}`;

  const fullText = transcriptData.fullText || transcriptData.rawTranscript || (typeof transcriptData === 'string' ? transcriptData : '');
  const timestampedText = transcriptData.timestampedText || fullText;
  const words = transcriptData.wordCount || fullText.split(/\s+/).filter(Boolean).length;

  const result = {
    success: true,
    videoId: cleanId,
    metadata: transcriptData.metadata || {
      title: `YouTube Lecture (${cleanId})`,
      author: 'YouTube Instructor',
      thumbnail: `https://img.youtube.com/vi/${cleanId}/hqdefault.jpg`,
      videoUrl: `https://www.youtube.com/watch?v=${cleanId}`
    },
    language: transcriptData.language || lang,
    isAutoGenerated: Boolean(transcriptData.isAutoGenerated),
    wordCount: words,
    timestampedText,
    fullText,
    rawItems: transcriptData.rawItems || []
  };

  cache.set(cacheKey, result, 30 * 24 * 60 * 60 * 1000); // 30 days
  return true;
}

