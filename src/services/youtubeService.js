const fs = require('fs');
const path = require('path');
const { YoutubeTranscript } = require('youtube-transcript');

const ROOT_DATA_DIR = process.env.DATA_DIR || path.join(__dirname, '../../data');
const CACHE_FILE_PATH = path.join(ROOT_DATA_DIR, 'transcripts_cache.json');
const LECTURE_TRANSCRIPTS_PATH = path.join(ROOT_DATA_DIR, 'lecture_transcripts.json');
const LIBRARY_PATH = path.join(ROOT_DATA_DIR, 'library.json');

/**
 * Multi-Tier Request & Result Cache (In-Memory L1 + Persistent Disk L2 + Database Lookup L3)
 * with TTL and Rate-Limit Cooldown Tracker
 */
class TranscriptCache {
  constructor(defaultTtlMs = 60 * 60 * 1000) {
    this.cache = new Map();
    this.defaultTtlMs = defaultTtlMs;
    this.maxEntries = 500;
    this.rateLimitCooldownUntil = 0;
    this.lastCooldownReason = '';
    this.cacheFilePath = CACHE_FILE_PATH;
    this.loadPersistentCache();
  }

  loadPersistentCache() {
    try {
      if (fs.existsSync(this.cacheFilePath)) {
        const raw = fs.readFileSync(this.cacheFilePath, 'utf-8');
        const diskData = JSON.parse(raw);
        const now = Date.now();
        for (const [key, entry] of Object.entries(diskData)) {
          if (entry && entry.expiresAt && entry.expiresAt > now) {
            this.cache.set(key, entry);
          }
        }
      }
    } catch {
      // Ignore disk cache load error gracefully
    }

    // Populate cache from existing saved lectures in lecture_transcripts.json
    try {
      if (fs.existsSync(LECTURE_TRANSCRIPTS_PATH)) {
        const raw = fs.readFileSync(LECTURE_TRANSCRIPTS_PATH, 'utf-8');
        const lectures = JSON.parse(raw);
        if (Array.isArray(lectures)) {
          for (const item of lectures) {
            const vidId = item.videoId || extractVideoId(item.sourceUrl);
            if (vidId && (item.fullText || item.rawTranscript)) {
              const fullText = item.fullText || item.rawTranscript || '';
              const lang = item.language || 'en';
              const cacheKey = `yt_transcript_${vidId}_${lang}`;
              if (!this.cache.has(cacheKey)) {
                this.cache.set(cacheKey, {
                  value: {
                    success: true,
                    videoId: vidId,
                    metadata: {
                      title: item.title || `Lecture (${vidId})`,
                      author: item.instructor || 'Course Instructor',
                      thumbnail: `https://img.youtube.com/vi/${vidId}/hqdefault.jpg`,
                      videoUrl: item.sourceUrl || `https://www.youtube.com/watch?v=${vidId}`
                    },
                    language: lang,
                    isAutoGenerated: false,
                    wordCount: item.wordCount || fullText.split(/\s+/).filter(Boolean).length,
                    timestampedText: item.timestampedText || '',
                    fullText,
                    rawItems: item.transcriptLines || []
                  },
                  expiresAt: Date.now() + (30 * 24 * 60 * 60 * 1000), // 30 days
                  createdAt: Date.now()
                });
              }
            }
          }
        }
      }
    } catch {
      // Ignore gracefully
    }
  }

  savePersistentCache() {
    try {
      const dir = path.dirname(this.cacheFilePath);
      if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
      }
      const diskData = {};
      const now = Date.now();
      for (const [key, entry] of this.cache.entries()) {
        if (key.startsWith('yt_transcript_') && entry && entry.expiresAt > now) {
          diskData[key] = entry;
        }
      }
      fs.writeFileSync(this.cacheFilePath, JSON.stringify(diskData, null, 2), 'utf-8');
    } catch {
      // Ignore gracefully if disk is unwritable or unavailable
    }
  }

  findInDatabase(videoId) {
    const transcriptPaths = [
      LECTURE_TRANSCRIPTS_PATH,
      path.join(__dirname, '../../data/lecture_transcripts.json')
    ].filter((p, idx, arr) => arr.indexOf(p) === idx);

    for (const p of transcriptPaths) {
      try {
        if (fs.existsSync(p)) {
          const raw = fs.readFileSync(p, 'utf-8');
          const lectures = JSON.parse(raw);
          if (Array.isArray(lectures)) {
            const match = lectures.find(l => l.videoId === videoId || (l.sourceUrl && l.sourceUrl.includes(videoId)));
            if (match && (match.fullText || match.rawTranscript)) {
              const fullText = match.fullText || match.rawTranscript || '';
              return {
                success: true,
                videoId,
                metadata: {
                  title: match.title || `Lecture (${videoId})`,
                  author: match.instructor || 'Course Instructor',
                  thumbnail: `https://img.youtube.com/vi/${videoId}/hqdefault.jpg`,
                  videoUrl: match.sourceUrl || `https://www.youtube.com/watch?v=${videoId}`
                },
                language: match.language || 'en',
                isAutoGenerated: false,
                wordCount: match.wordCount || fullText.split(/\s+/).filter(Boolean).length,
                timestampedText: match.timestampedText || '',
                fullText,
                rawItems: match.transcriptLines || []
              };
            }
          }
        }
      } catch {
        // Ignore gracefully
      }
    }

    const libPaths = [
      LIBRARY_PATH,
      path.join(__dirname, '../../data/library.json')
    ].filter((p, idx, arr) => arr.indexOf(p) === idx);

    for (const p of libPaths) {
      try {
        if (fs.existsSync(p)) {
          const raw = fs.readFileSync(p, 'utf-8');
          const lib = JSON.parse(raw);
          if (Array.isArray(lib)) {
            const match = lib.find(l => l.videoId === videoId || (l.videoUrl && l.videoUrl.includes(videoId)));
            if (match && match.transcriptText) {
              return {
                success: true,
                videoId,
                metadata: {
                  title: match.lectureTitle || match.topicTitle || `Lecture (${videoId})`,
                  author: 'Course Instructor',
                  thumbnail: `https://img.youtube.com/vi/${videoId}/hqdefault.jpg`,
                  videoUrl: match.videoUrl || `https://www.youtube.com/watch?v=${videoId}`
                },
                language: 'en',
                isAutoGenerated: false,
                wordCount: match.transcriptText.split(/\s+/).filter(Boolean).length,
                timestampedText: match.transcriptText,
                fullText: match.transcriptText,
                rawItems: []
              };
            }
          }
        }
      } catch {
        // Ignore gracefully
      }
    }

    return null;
  }

  get(key) {
    const entry = this.cache.get(key);
    if (!entry) {
      if (key.startsWith('yt_transcript_')) {
        if (fs.existsSync(this.cacheFilePath)) {
          try {
            const raw = fs.readFileSync(this.cacheFilePath, 'utf-8');
            const diskData = JSON.parse(raw);
            const diskEntry = diskData[key];
            if (diskEntry && diskEntry.expiresAt && diskEntry.expiresAt > Date.now()) {
              this.cache.set(key, diskEntry);
              return diskEntry.value;
            }
          } catch {
            // Ignore
          }
        }
        const parts = key.split('_');
        const vidId = parts[2];
        if (vidId) {
          const fromDb = this.findInDatabase(vidId);
          if (fromDb) {
            this.set(key, fromDb, 30 * 24 * 60 * 60 * 1000);
            return fromDb;
          }
        }
      }
      return null;
    }
    if (Date.now() > entry.expiresAt) {
      this.cache.delete(key);
      if (key.startsWith('yt_transcript_')) {
        this.savePersistentCache();
      }
      return null;
    }
    return entry.value;
  }

  set(key, value, ttlMs = this.defaultTtlMs) {
    // Evict oldest entry if at capacity
    if (this.cache.size >= this.maxEntries) {
      const oldestKey = this.cache.keys().next().value;
      if (oldestKey) this.cache.delete(oldestKey);
    }

    this.cache.set(key, {
      value,
      expiresAt: Date.now() + ttlMs,
      createdAt: Date.now()
    });

    if (key.startsWith('yt_transcript_')) {
      this.savePersistentCache();
    }
  }

  has(key) {
    return this.get(key) !== null;
  }

  delete(key) {
    const deleted = this.cache.delete(key);
    if (key.startsWith('yt_transcript_')) {
      this.savePersistentCache();
    }
    return deleted;
  }

  clear() {
    this.cache.clear();
    this.rateLimitCooldownUntil = 0;
    this.lastCooldownReason = '';
    try {
      if (fs.existsSync(this.cacheFilePath)) {
        fs.unlinkSync(this.cacheFilePath);
      }
    } catch {
      // Ignore
    }
  }

  setRateLimitCooldown(durationMs = 60 * 1000, reason = 'YouTube IP rate limit / Captcha challenge detected') {
    this.rateLimitCooldownUntil = Date.now() + durationMs;
    this.lastCooldownReason = reason;
  }

  isCooldownActive() {
    return Date.now() < this.rateLimitCooldownUntil;
  }

  getCooldownRemainingSec() {
    if (!this.isCooldownActive()) return 0;
    return Math.ceil((this.rateLimitCooldownUntil - Date.now()) / 1000);
  }

  getStats() {
    return {
      size: this.cache.size,
      maxEntries: this.maxEntries,
      isCooldownActive: this.isCooldownActive(),
      cooldownRemainingSec: this.getCooldownRemainingSec(),
      lastCooldownReason: this.lastCooldownReason
    };
  }
}

