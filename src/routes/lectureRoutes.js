const express = require('express');
const router = express.Router();
const multer = require('multer');
const path = require('path');
const fs = require('fs');
const { subjects, getAllSubjects, getSubjectById, ROOT_DIR } = require('../config/subjects');
const youtubeService = require('../services/youtubeService');
const aiService = require('../services/aiService');
const fileService = require('../services/fileService');
const progressService = require('../services/progressService');

const upload = multer({
  dest: path.join(ROOT_DIR, 'uploads'),
  limits: { fileSize: 50 * 1024 * 1024 } // 50MB
});

// Add Lecture Page
router.get('/add-lecture', (req, res) => {
  const selectedSubjectId = req.query.subject || '';
  res.render('pages/add-lecture', {
    title: 'Add Lecture - CSE Study Hub',
    subjects: getAllSubjects(),
    selectedSubjectId,
    activeNav: 'add-lecture',
    aiConfigured: aiService.isConfigured()
  });
});

// Subject-specific Add Lecture URL
router.get('/subject/:id/add-lecture', (req, res) => {
  const subject = getSubjectById(req.params.id);
  if (!subject) return res.redirect('/add-lecture');

  res.render('pages/add-lecture', {
    title: `Add Lecture: ${subject.name}`,
    subjects: getAllSubjects(),
    selectedSubjectId: subject.id,
    activeNav: subject.id,
    aiConfigured: aiService.isConfigured()
  });
});

// API: Fetch Transcript from YouTube
router.post('/api/transcript', async (req, res) => {
  try {
    const { videoUrl, language } = req.body;
    if (!videoUrl) {
      return res.status(400).json({ success: false, error: 'Video URL or ID is required.' });
    }

    const result = await youtubeService.fetchTranscript(videoUrl, language || 'en');
    res.json(result);
  } catch (err) {
    res.status(500).json({ success: false, error: err.message });
  }
});

// API: Cache transcript retrieved from browser
router.post('/api/cache-transcript', async (req, res) => {
  try {
    const { videoId, fullText, timestampedText, metadata, language, rawItems, isAutoGenerated } = req.body;
    if (!videoId || (!fullText && !timestampedText)) {
      return res.status(400).json({ success: false, error: 'Video ID and transcript text are required.' });
    }

    const cached = youtubeService.cacheTranscript(videoId, {
      fullText,
      timestampedText: timestampedText || fullText,
      metadata,
      language: language || 'en',
      rawItems,
      isAutoGenerated
    }, language || 'en');

    res.json({ success: Boolean(cached) });
  } catch (err) {
    res.status(500).json({ success: false, error: err.message });
  }
});

// API: Upload manual transcript file
router.post('/api/upload-transcript-file', upload.single('transcriptFile'), async (req, res) => {
  try {
    if (!req.file) {
      return res.status(400).json({ success: false, error: 'No file uploaded.' });
    }
    const transcriptionService = require('../services/transcriptionService');
    const videoId = req.body.videoId || null;
    const result = await transcriptionService.transcribeTextFile({
      file: req.file,
      fileName: req.file.originalname,
      videoId
    });
    res.json({
      success: true,
      text: result.fullText || result.timestampedText,
      fullText: result.fullText,
      timestampedText: result.timestampedText,
      wordCount: result.wordCount,
      timestampedTranscript: result.timestampedTranscript
    });
  } catch (err) {
    res.status(500).json({ success: false, error: err.message });
  }
});

// API: Upload Media (Audio/Video Speech-to-Text)
