/**
 * Strategy 0: Supadata API (Bypasses Render/Cloud IP blocks reliably)
 */
async function fetchViaSupadata(videoId, requestedLang = 'en') {
  const apiKey = process.env.SUPADATA_API_KEY;
  if (!apiKey || !apiKey.trim()) return null;

  try {
    const url = `https://api.supadata.ai/v1/youtube/transcript?videoId=${encodeURIComponent(videoId)}&lang=${encodeURIComponent(requestedLang)}`;
    const res = await fetch(url, {
      headers: {
        'x-api-key': apiKey.trim(),
        'Accept': 'application/json'
      }
    });

    if (!res.ok) return null;
    const data = await res.json();

    if (Array.isArray(data.content) && data.content.length > 0) {
      const items = data.content.map(c => ({
        text: decodeEntities(c.text || '').trim(),
        offset: Math.round(c.offset || 0),
        offsetSec: Math.floor((c.offset || 0) / 1000),
        duration: Math.round(c.duration || 0),
        lang: data.lang || requestedLang
      })).filter(i => i.text);

      if (items.length > 0) {
        return {
          items,
          language: data.lang || requestedLang,
          isAutoGenerated: false
        };
      }
    }
  } catch {
    return null;
  }
  return null;
}
