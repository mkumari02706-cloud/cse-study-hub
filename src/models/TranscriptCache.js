const { createModel } = require('./baseModel');

/**
 * TranscriptCache Model (MongoDB / Mongoose-compatible)
 * Caches YouTube transcripts by videoId and language to avoid repeated network requests
 * and mitigate rate-limiting across server restarts.
 */
const TranscriptCache = createModel('TranscriptCache', 'transcript_cache', {
  videoId: { type: String, required: true },
  language: { type: String, default: 'en' },
  title: { type: String, default: '' },
  author: { type: String, default: '' },
  videoUrl: { type: String, default: '' },
  thumbnail: { type: String, default: '' },
  isAutoGenerated: { type: Boolean, default: false },
  wordCount: { type: Number, default: 0 },
  timestampedText: { type: String, default: '' },
  fullText: { type: String, default: '' },
  rawItems: { type: Array, default: [] },
  expiresAt: { type: Number, default: 0 },
  createdAt: { type: String, default: () => new Date().toISOString() },
  updatedAt: { type: String, default: () => new Date().toISOString() }
});

module.exports = TranscriptCache;
